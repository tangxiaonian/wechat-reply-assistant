import type { Contact, ReplyInput } from "../types/workspace";
import { groupReplies } from "./groupReplies";

/** Preset scene preview only: arbitrary manual context requires the configured model. */
export function demoReplies(contact: Contact, input: ReplyInput): string[] {
  if (contact.kind === "group") {
    return groupReplies(contact, input);
  }
  if (input.manualTranscript) {
    throw new Error("手动上下文需要连接模型；演示候选只适用于示例会话");
  }
  if (input.task === "rewrite") {
    if (contact.id === "demo-friend") {
      return [
        "好呀，我周六下午有空，一起去吧。",
        "可以呀，周六下午我没有其他安排。",
        "想去，我下午有时间。",
      ];
    }
    if (contact.id === "demo-work") {
      return [
        "资料已经在整理了，我再核对一下剩余内容。",
        "我正在整理，确认好进度后就回复你。",
        "我这边正在整理，稍后同步进度。",
      ];
    }
    return [
      "理解，那我们先看看您最想保留的核心部分。",
      "可以，您最关注的是哪部分功能？我再梳理一下。",
      "我们先明确必须保留的功能，再一起看怎么精简。",
    ];
  }
  if (input.task === "follow_up") {
    return contact.id === "demo-friend"
      ? [
          "想确认一下，周六还是在地铁口碰面吗？",
          "周六看展的安排还照旧吗？",
          "周六几点碰面，你这边更方便？",
        ]
      : contact.id === "demo-work"
        ? [
            "资料还在整理，我核对好进度后再同步你。",
            "关于资料，我想再确认一下你最晚的使用时间。",
            "我这边继续整理，有进展及时跟你说。",
          ]
        : [
            "周女士，想再确认一下，精简方案里您最关注哪部分？",
            "我们可以先围绕核心功能梳理，您看这样方便吗？",
            "关于预算，我想先和您对齐必需的功能，再考虑精简方式。",
          ];
  }
  if (contact.id === "demo-work") {
    return input.tone === "正式"
      ? [
          "我先核对剩余内容，稍后给你准确的交付时间。",
          "收到，我正在整理。确认进度后，再同步下班前能给出的范围。",
          "我确认一下完成情况，尽快回复你初稿可以提供的时间。",
        ]
      : [
          "我先看下还差多少，马上给你个准信。",
          "我还在整理，先确认下进度，再告诉你下班前能给到哪一版。",
          "收到，我核对下剩余内容，等会儿跟你确认。",
        ];
  }
  if (contact.id === "demo-customer") {
    return input.tone === "温柔"
      ? [
          "可以理解，我们先把您最需要的核心功能保留下来。我再整理一版精简思路给您看。",
          "可以的，我先和您对齐核心需求，再看看哪些部分能分阶段来做。",
          "没问题，我们先围绕必须保留的功能梳理一下，再一起看精简后的方案。",
        ]
      : [
          "可以，我们先保留核心功能，其他部分按优先级精简。我整理后再和您确认。",
          "可以考虑分阶段实施。先把必须保留的功能对齐，我再核算精简后的方案。",
          "理解，我们先明确核心功能清单，再看哪些可以后置，具体费用我重新确认后回复您。",
        ];
  }
  const late = /半小时|两点半|晚一点/.test(input.background);
  const time = late ? "两点半" : "两点";
  const options = {
    自然: [
      `好呀，${late ? "我可能要晚半小时，" : ""}${time}在地铁口见可以吗？`,
      `${late ? "要不改成两点半？" : "可以，那就两点见。"}我直接到地铁口找你。`,
      `${late ? "我想去，不过得两点半才能到。" : "好，周六两点见。"}到时候地铁口碰面。`,
    ],
    温柔: [
      `好呀，我也挺想去的。${late ? "不过我得晚半小时，两点半见方便吗？" : "那我们两点在地铁口见。"}`,
      `${late ? "我两点半能到，你方便晚一点吗？" : "可以呀，两点见。"}周六一起慢慢逛。`,
      `${late ? "想跟你一起去，时间挪到两点半可以吗？" : "好呀，那就这样说定了，周六见。"}`,
    ],
    俏皮: [
      `看展搭子就位！${late ? "能申请延后半小时，两点半见吗？" : "两点地铁口集合。"}`,
      `收到，${late ? "能把集合时间挪到两点半吗？" : "两点准时集合！"}`,
      `${late ? "我得申请半小时缓冲，两点半见行不行？" : "安排上了，周六两点见！"}`,
    ],
    正式: [
      `可以，${late ? "我预计两点半到，是否方便调整一下时间？" : "周六两点在地铁口见。"}`,
      `${late ? "时间能否调整到两点半？地点仍在地铁口。" : "时间和地点都可以，周六见。"}`,
      `好的，${late ? "我这边需要晚半小时到，请确认是否方便。" : "我们按这个安排碰面。"}`,
    ],
  };
  return options[input.tone as keyof typeof options] ?? options["自然"];
}
